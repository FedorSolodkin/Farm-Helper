"""Бенчмарки категорий по региону. Синтетические значения: в пилоте считаются по витрине банка."""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Bench:
    category: str
    n_farms: int
    median_views_30d: float  # просмотров карточки за 30 дней
    median_cr: float  # конверсия просмотра в заказ
    p75_price: float  # 75-й перцентиль цены за единицу
    elasticity: float  # по модулю: на сколько % растёт объём при снижении цены на 1%
    demand_growth: float  # рост спроса категории к прошлым 4 неделям
    avg_farm_weekly_rev: float  # средняя недельная выручка фермера в категории, ₽
    group: str = ""  # смежные категории: подсказку «добавьте категорию» даём только «своим»


BENCHMARKS = {
    b.category: b
    for b in [
        Bench("Сыры", 14, 3500, 0.035, 2400, 1.3, 0.04, 22000, group="молочная"),
        Bench("Молочное", 21, 3000, 0.040, 700, 1.5, 0.02, 15000, group="молочная"),
        Bench("Мёд", 18, 2500, 0.030, 1000, 2.0, 0.35, 18000, group="пчеловодство"),
        Bench("Продукты пчеловодства", 9, 1500, 0.025, 3000, 1.2, 0.10, 8000, group="пчеловодство"),
        Bench("Овощи", 26, 2800, 0.040, 400, 1.4, 0.08, 16000, group="огород"),
        Bench("Тыква и бахча", 11, 1800, 0.045, 60, 1.3, 0.60, 14000, group="огород"),
        # слишком мало фермеров в выборке: k-анонимность отфильтрует категорию
        Bench("Мясо", 3, 2000, 0.030, 1200, 1.1, 0.50, 30000, group="мясо"),
    ]
}
